-- Animation of a wanderer of the hub: a villager pacing between two points of a street (or standing at its post).
-- The walk itself (waypoints, waits, mirroring and hop) is a `Patrol` component of the entity; this script only picks the
-- frame of the sprite: a two-frame walk while the entity moves, a two-frame idle (breathing) while it waits.
-- Demonstrates: reading the transform of an entity driven by a component, script properties set per entity in the scene,
--               `isometric.set_sprite_frame`, the frames being tiles of the town atlas (`idle_a`, `idle_b`, `walk_a`,
--               `walk_b`, generated by tools/demo/generate_village_tiles.py).

properties = {
    { name = "idle_a", type = "float", default = 0 },
    { name = "idle_b", type = "float", default = 0 },
    { name = "walk_a", type = "float", default = 0 },
    { name = "walk_b", type = "float", default = 0 },
    { name = "idle_period", type = "float", default = 0.8 },
    { name = "step_time", type = "float", default = 0.18, min = 0.01 },
}

-- The properties of the scene are the only values at runtime (the defaults above are editor metadata): `idle_period` is
-- optional there.
local period = 0.8
local last_x, last_y = 0, 0
local clock = 0
local idle_clock = 0
local shown = -1

local function show(frame)
    if frame ~= shown then
        shown = frame
        isometric.set_sprite_frame(entity_id, frame)
    end
end

function on_create()
    period = idle_period or period
    last_x, last_y = transform.get_position(entity_id)
    -- Not all in step: the villagers start at different points of their breath.
    idle_clock = (last_x * 0.37 + last_y * 0.11) % period
end

function on_update(dt)
    local x, y = transform.get_position(entity_id)
    local moving = math.abs(x - last_x) > 1e-5 or math.abs(y - last_y) > 1e-5
    last_x, last_y = x, y
    if moving then
        clock = clock + dt
        show(math.floor(clock / step_time) % 2 == 0 and walk_a or walk_b)
    else
        idle_clock = idle_clock + dt
        show(math.floor(idle_clock / (period * 0.5)) % 2 == 0 and idle_a or idle_b)
    end
end
