-- Wanderer of the hub: a villager pacing between two points of a street, stopping at each end; with both points equal it
-- stands at its post (a merchant) and only breathes.
-- Demonstrates: a plain Lua loop on the transform (no pathfinding, no physics), script properties set per entity in
--               the scene (`ax`, `ay`, `bx`, `by`, `speed`, `wait`), a sprite mirrored toward its direction, a hop while walking,
--               `isometric.set_sprite_frame` for a two-frame idle (breathing) and a two-frame walk of the character, the frames
--               being tiles of the town atlas (`idle_a`, `idle_b`, `walk_a`, `walk_b`, generated by textures/generate_village_tiles.py).

properties = {
    { name = "ax", type = "float", default = 0.0 },
    { name = "ay", type = "float", default = 0.0 },
    { name = "bx", type = "float", default = 1.0 },
    { name = "by", type = "float", default = 0.0 },
    { name = "speed", type = "float", default = 1.2 },
    { name = "wait", type = "float", default = 1.5 },
    { name = "idle_a", type = "float", default = 0 },
    { name = "idle_b", type = "float", default = 0 },
    { name = "walk_a", type = "float", default = 0 },
    { name = "walk_b", type = "float", default = 0 },
    { name = "idle_period", type = "float", default = 0.8 },
}

-- The properties of the scene are the only values at runtime (the defaults above are editor metadata): `idle_period` is
-- optional there.
local STEP_TIME = 0.18
local period = 0.8
local sprite_scale = 1.0
local x, y = 0, 0
local to_b = true
local wait_left = 0
local clock = 0
local idle_clock = 0
local shown = -1

local function show(frame)
    if frame ~= shown then
        shown = frame
        isometric.set_sprite_frame(entity_id, frame)
    end
end

function on_create()
    sprite_scale = transform.get_scale(entity_id)
    period = idle_period or period
    x, y = ax, ay
    -- Not all in step: the villagers start at different points of their breath.
    idle_clock = (ax * 0.37 + ay * 0.11) % period
    transform.set_position(entity_id, x, y, 0.5)
end

function on_update(dt)
    local tx, ty = to_b and bx or ax, to_b and by or ay
    local moving = false
    if wait_left > 0 then
        wait_left = wait_left - dt
    else
        local dx, dy = tx - x, ty - y
        local dist = math.sqrt(dx * dx + dy * dy)
        local step = speed * dt
        if dist <= step then
            x, y = tx, ty
            to_b = not to_b
            wait_left = wait
        else
            x, y = x + dx / dist * step, y + dy / dist * step
            moving = true
            if dx ~= 0 then
                transform.set_scale(entity_id, dx < 0 and -sprite_scale or sprite_scale, sprite_scale, 1)
            end
        end
    end
    if moving then
        clock = clock + dt
        show(math.floor(clock / STEP_TIME) % 2 == 0 and walk_a or walk_b)
    else
        idle_clock = idle_clock + dt
        show(math.floor(idle_clock / (period * 0.5)) % 2 == 0 and idle_a or idle_b)
    end
    transform.set_position(entity_id, x, y + (moving and math.abs(math.sin(clock * 9)) * 0.06 or 0), 0.5)
end
